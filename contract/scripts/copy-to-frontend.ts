/**
 * Copy public deploy artifacts into the React app so the UI can import them.
 *
 * Source:  contract/deployed/*
 * Dest:    frontend/src/contracts   (typed TS/JSON imports)
 *          frontend/public/zk/bidshield  (static ZK keys for a local proof server)
 *
 * Never copies deployed/private (organizer secret, bidder secret).
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CONTRACT_ROOT = path.resolve(__dirname, '..');
const REPO_ROOT = path.resolve(CONTRACT_ROOT, '..');
const DEPLOYED = path.join(CONTRACT_ROOT, 'deployed');
const FRONTEND_CONTRACTS = path.join(REPO_ROOT, 'frontend', 'src', 'contracts');
const FRONTEND_ZK = path.join(REPO_ROOT, 'frontend', 'public', 'zk', 'bidshield');

const PUBLIC_FILES = [
  'preview.json',
  'frontend-config.json',
  'circuits.json',
  'contract-info.json',
] as const;

function copyFileIfExists(src: string, dest: string): boolean {
  if (!fs.existsSync(src)) return false;
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
  return true;
}

function writeIndexTs(copied: string[]): void {
  const lines = [
    '/** Auto-generated by contract/scripts/copy-to-frontend.ts — do not edit by hand. */',
    '',
    "import previewJson from './preview.json';",
    "import frontendConfigJson from './frontend-config.json';",
    "import circuitsJson from './circuits.json';",
    '',
    'export type BidShieldPreview = {',
    "  name: string;",
    "  network: string;",
    "  networkId: string;",
    "  contractAddress: string;",
    "  deploymentTxHash: string | null;",
    "  deployer: string;",
    "  deployedAt: string;",
    "  explorer: string;",
    "  endpoints: {",
    "    indexer: string;",
    "    indexerWS: string;",
    "    node: string;",
    "    proofServer: string;",
    "  };",
    "  circuits: string[];",
    "  witnesses: string[];",
    "  privateStateId: string;",
    "  zkAssetsPath: string;",
    "  tender: {",
    "    tenderId: string;",
    "    policyHash: string;",
    "    commitStart: string;",
    "    commitEnd: string;",
    "    revealEnd: string;",
    "    timeUnit: string;",
    "  };",
    '};',
    '',
    'export type BidShieldFrontendConfig = {',
    "  VITE_MIDNIGHT_NETWORK: string;",
    "  VITE_CONTRACT_ADDRESS: string;",
    "  VITE_INDEXER_HTTP: string;",
    "  VITE_INDEXER_WS: string;",
    "  VITE_NODE_URL: string;",
    "  VITE_PROOF_SERVER: string;",
    "  VITE_TENDER_ID: string;",
    "  VITE_POLICY_HASH: string;",
    "  VITE_COMMIT_START: string;",
    "  VITE_COMMIT_END: string;",
    "  VITE_REVEAL_END: string;",
    "  VITE_PRIVATE_STATE_ID: string;",
    "  VITE_ZK_ASSETS_BASE: string;",
    '};',
    '',
    'export const preview = previewJson as BidShieldPreview;',
    'export const frontendConfig = frontendConfigJson as BidShieldFrontendConfig;',
    'export const circuits = circuitsJson;',
    '',
    'export const CONTRACT_ADDRESS = preview.contractAddress;',
    'export const NETWORK = preview.network;',
    'export const TENDER = preview.tender;',
    'export const ZK_ASSETS_BASE = frontendConfig.VITE_ZK_ASSETS_BASE;',
    '',
  ];

  if (copied.includes('contract-info.json')) {
    lines.splice(5, 0, "import contractInfoJson from './contract-info.json';");
    lines.push('export const contractInfo = contractInfoJson;');
    lines.push('');
  }

  fs.writeFileSync(path.join(FRONTEND_CONTRACTS, 'index.ts'), `${lines.join('\n')}\n`);
}

export function copyDeployedOutputs(): { copied: string[]; skipped: string[] } {
  if (!fs.existsSync(DEPLOYED)) {
    throw new Error(`No deploy outputs at ${DEPLOYED}. Run npm run deploy:preview first.`);
  }

  fs.mkdirSync(FRONTEND_CONTRACTS, { recursive: true });
  const copied: string[] = [];
  const skipped: string[] = [];

  for (const name of PUBLIC_FILES) {
    const ok = copyFileIfExists(path.join(DEPLOYED, name), path.join(FRONTEND_CONTRACTS, name));
    (ok ? copied : skipped).push(name);
  }

  const infoSrc = path.join(CONTRACT_ROOT, 'managed', 'bidshield', 'compiler', 'contract-info.json');
  if (copyFileIfExists(infoSrc, path.join(FRONTEND_CONTRACTS, 'contract-info.json'))) {
    if (!copied.includes('contract-info.json')) copied.push('contract-info.json');
  }

  const zkSrc = path.join(DEPLOYED, 'zk-assets');
  if (fs.existsSync(zkSrc)) {
    fs.rmSync(FRONTEND_ZK, { recursive: true, force: true });
    fs.cpSync(zkSrc, FRONTEND_ZK, { recursive: true });
    copied.push('zk-assets → public/zk/bidshield');
  }

  const managedContract = path.join(CONTRACT_ROOT, 'managed', 'bidshield', 'contract');
  if (fs.existsSync(managedContract)) {
    const dest = path.join(FRONTEND_CONTRACTS, 'managed');
    fs.rmSync(dest, { recursive: true, force: true });
    fs.cpSync(managedContract, dest, { recursive: true });
    copied.push('managed/contract → src/contracts/managed');
  }

  writeIndexTs(copied);

  const gitignore = path.join(FRONTEND_CONTRACTS, '.gitignore');
  if (!fs.existsSync(gitignore)) {
    fs.writeFileSync(
      gitignore,
      `# Generated by contract/scripts/copy-to-frontend.ts
# Keep the barrel so the app typechecks before the first deploy.
# JSON artifacts are copied after deploy — commit them if you want a frozen Preview address.
`,
    );
  }

  return { copied, skipped };
}

const isDirect = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirect) {
  try {
    const result = copyDeployedOutputs();
    console.log('Copied public deploy outputs → frontend/src/contracts');
    for (const name of result.copied) console.log(`  + ${name}`);
    for (const name of result.skipped) console.log(`  - skipped (missing): ${name}`);
    console.log('  (private organizer secrets were not copied)');
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
